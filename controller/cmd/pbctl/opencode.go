func ensureFastPool(c *client, o *out) error {
	raw, err := c.do(http.MethodGet, "/admin/pools", nil)
	if err != nil {
		if isHTTP404(err) {
			fmt.Fprintln(o.w, "warning: controller has no pools API (older controller); skipping the fast pool")
			return nil
		}
		return err
	}
	var list ocPoolList
	if err := json.Unmarshal(raw, &list); err != nil {
		return err
	}
	for _, p := range list.Pools {
		if p.Name == ocFastPoolName {
			return nil
		}
	}
	pool := ocPool{Name: ocFastPoolName, Description: ocFastPoolDesc, Routing: "spread"}
	if _, err := c.do(http.MethodPut, "/admin/pools/"+ocFastPoolName, pool); err != nil {
		if isHTTP404(err) {
			fmt.Fprintln(o.w, "warning: controller has no pools API (older controller); skipping the fast pool")
			return nil
		}
		return err
	}
	fmt.Fprintln(o.w, "created pool fast (routing spread)")
	return nil
}

