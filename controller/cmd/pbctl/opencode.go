// clusterState is the cluster-facing input to config/agent generation.
type clusterState struct {
	Models []ocModel
	Nodes  []ocAdminNode
}

func fetchClusterState(c *client) (clusterState, error) {
	var st clusterState
	modelsRaw, err := c.request(http.MethodGet, "/v1/models", nil, c.apiKey)
	if err != nil {
		return st, err
	}
	var ml struct {
		Data []ocModel `json:"data"`
	}
	if err := json.Unmarshal(modelsRaw, &ml); err != nil {
		return st, err
	}
	st.Models = ml.Data

	nodesRaw, err := c.do(http.MethodGet, "/admin/nodes", nil)
	if err != nil {
		return st, err
	}
	if err := json.Unmarshal(nodesRaw, &st.Nodes); err != nil {
		return st, err
	}
	return st, nil
}

// isHTTP404 recognizes the "HTTP 404: ..." errors client.request formats,
// used to detect an older controller that has no pools/prewarm API yet.
func isHTTP404(err error) bool {
	return err != nil && strings.Contains(err.Error(), "HTTP 404")
}

// aliasedNode is one phone with an alias, as seen through /v1/models
// (node/<alias> entries) and cross-referenced with /admin/nodes for its
// device string.
type aliasedNode struct {
	Alias       string
	NodeID      string
	Device      string
	ServedModel string
	Ready       bool
	NodesReady  int
}

// aliasedNodesFromModels lists every node/<alias> entry in models, filling
// in device info from nodes when the alias matches.
func aliasedNodesFromModels(models []ocModel, nodes []ocAdminNode) []aliasedNode {
	byAlias := map[string]ocAdminNode{}
	for _, n := range nodes {
		if n.Alias != "" {
			byAlias[n.Alias] = n
		}
	}
	var out []aliasedNode
	for _, m := range models {
		if m.kindOrDefault() != "node" {
			continue
		}
		alias := strings.TrimPrefix(m.ID, "node/")
		an := aliasedNode{Alias: alias, ServedModel: m.Model, Ready: m.Ready, NodesReady: m.Nodes}
		if n, ok := byAlias[alias]; ok {
			an.NodeID = n.ID
			an.Device = n.device()
			if an.ServedModel == "" {
				an.ServedModel = n.servedModel()
			}
		}
		out = append(out, an)
	}
	sort.Slice(out, func(i, j int) bool { return out[i].Alias < out[j].Alias })
	return out
}

// modelContextLimit is the node ctx if known, else the 16384 default.
func modelContextLimit(m ocModel, nodes []ocAdminNode) int {
	switch m.kindOrDefault() {
	case "node":
		alias := strings.TrimPrefix(m.ID, "node/")
		for _, n := range nodes {
			if n.Alias == alias || n.ID == alias {
				if c := n.ctxSize(); c > 0 {
					return c
				}
			}
		}
	case "model":
		best := 0
		for _, n := range nodes {
			if n.servedModel() == m.ID && n.ctxSize() > best {
				best = n.ctxSize()
			}
		}
		if best > 0 {
			return best
		}
	}
	return ocDefaultCtx
}

func modelDisplayName(m ocModel, nodes []ocAdminNode) string {
	switch m.kindOrDefault() {
	case "auto":
		return "Auto (any ready phone)"
	case "pool":
		if m.Description != "" {
			return m.Description
		}
		return "Pool " + strings.TrimPrefix(m.ID, "pool/")
	case "node":
		alias := strings.TrimPrefix(m.ID, "node/")
		served := m.Model
		if served == "" {
			for _, n := range nodes {
				if n.Alias == alias {
					served = n.servedModel()
				}
			}
		}
		if served == "" {
			served = "no model"
		}
		return fmt.Sprintf("Phone %s (%s)", alias, served)
	default:
		return m.ID
	}
}

