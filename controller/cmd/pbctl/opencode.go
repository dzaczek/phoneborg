func opencodeWatch(c *client, o *out, args []string) error {
	fs := flag.NewFlagSet("opencode watch", flag.ContinueOnError)
	fs.SetOutput(io.Discard)
	dir := fs.String("dir", ".", "project directory")
	interval := fs.Duration("interval", 15*time.Second, "sync interval")
	if err := fs.Parse(args); err != nil {
		return fmt.Errorf("opencode watch: %w", err)
	}
	if fs.NArg() != 0 {
		return errUsage
	}
	if *interval <= 0 {
		return fmt.Errorf("opencode watch: -interval must be positive")
	}

	ctx, stop := signal.NotifyContext(context.Background(), os.Interrupt, syscall.SIGTERM)
	defer stop()

	tick := func() {
		res, err := runOpenCodeSync(c, *dir)
		ts := time.Now().Format(time.RFC3339)
		if err != nil {
			fmt.Fprintln(o.w, ts, "sync error:", err)
			return
		}
		if res.changed() || len(res.Warnings) > 0 {
			fmt.Fprintln(o.w, ts, res.summary())
			for _, w := range res.Warnings {
				fmt.Fprintln(o.w, "warning:", w)
			}
		}
	}
	tick()
	ticker := time.NewTicker(*interval)
	defer ticker.Stop()
	for {
		select {
		case <-ctx.Done():
			return nil
		case <-ticker.C:
			tick()
		}
	}
}

func opencodeStatus(c *client, o *out, args []string) error {
	fs := flag.NewFlagSet("opencode status", flag.ContinueOnError)
	fs.SetOutput(io.Discard)
	dir := fs.String("dir", ".", "project directory")
	if err := fs.Parse(args); err != nil {
		return fmt.Errorf("opencode status: %w", err)
	}
	if fs.NArg() != 0 {
		return errUsage
	}

	manifest, ok, err := loadManifest(*dir)
	if err != nil {
		return err
	}
	if !ok {
		return fmt.Errorf("no %s; run 'pbctl opencode init' first", filepath.Join(*dir, ocManifestPath))
	}

	modelsRaw, err := c.request(http.MethodGet, "/v1/models", nil, c.apiKey)
	if err != nil {
		return err
	}
	var ml struct {
		Data []ocModel `json:"data"`
	}
	if err := json.Unmarshal(modelsRaw, &ml); err != nil {
		return err
	}
	byID := map[string]ocModel{}
	for _, m := range ml.Data {
		byID[m.ID] = m
	}

	names := manifest.agentNames()
	if len(names) == 0 {
		fmt.Fprintln(o.w, "no managed agents; run 'pbctl opencode init' or 'sync'")
	} else {
		var rows [][]string
		for _, name := range names {
			target := targetForAgentName(name)
			m, found := byID[target]
			served, nodesReady, status := "-", "0", "missing"
			if found {
				nodesReady = strconv.Itoa(m.Nodes)
				if m.Model != "" {
					served = m.Model
				}
				if m.Nodes > 0 {
					status = "ready"
				} else {
					status = "no nodes"
				}
			}
			rows = append(rows, []string{name, target, served, nodesReady, status})
		}
		o.table("NAME\tTARGET\tSERVED MODEL\tNODES READY\tSTATUS", rows)
	}
	fmt.Fprintf(o.w, "\nprovider %s, baseURL %s\n", manifest.Provider, manifest.BaseURL)
	return nil
}

func summarizePrewarmResults(results []ocPrewarmNodeResult) (ok, ms, errs string) {
	if len(results) == 0 {
		return "0/0", "-", ""
	}
	okCount, maxMS := 0, 0
	var errList []string
	for _, r := range results {
		if r.OK {
			okCount++
		}
		if r.MS > maxMS {
			maxMS = r.MS
		}
		if r.Error != "" {
			errList = append(errList, r.Error)
		}
	}
	return fmt.Sprintf("%d/%d", okCount, len(results)), strconv.Itoa(maxMS), strings.Join(errList, "; ")
}

func opencodePrewarm(c *client, o *out, args []string) error {
	fs := flag.NewFlagSet("opencode prewarm", flag.ContinueOnError)
	fs.SetOutput(io.Discard)
	dir := fs.String("dir", ".", "project directory")
	if err := fs.Parse(args); err != nil {
		return fmt.Errorf("opencode prewarm: %w", err)
	}
	if fs.NArg() != 0 {
		return errUsage
	}

	manifest, ok, err := loadManifest(*dir)
	if err != nil {
		return err
	}
	if !ok {
		return fmt.Errorf("no %s; run 'pbctl opencode init' first", filepath.Join(*dir, ocManifestPath))
	}

	names := manifest.agentNames()
	if len(names) == 0 {
		fmt.Fprintln(o.w, "no managed agents to prewarm")
		return nil
	}

	fmt.Fprintln(o.w, "note: opencode appends environment details to the system prompt, so prewarm mostly helps agents with long prompts or tools")
	var rows [][]string
	for _, name := range names {
		path := filepath.Join(*dir, ocAgentDirName, name+".md")
		data, err := os.ReadFile(path)
		if err != nil {
			return err
		}
		model, body, err := parseAgentFrontmatter(string(data))
		if err != nil {
			return fmt.Errorf("%s: %w", path, err)
		}
		target := strings.TrimPrefix(model, manifest.Provider+"/")
		req := ocPrewarmRequest{Target: target, Messages: []ocChatMessage{{Role: "system", Content: body}}}
		raw, err := c.do(http.MethodPost, "/admin/prewarm", req)
		if err != nil {
			rows = append(rows, []string{name, target, "-", "-", err.Error()})
			continue
		}
		var pr ocPrewarmResponse
		if err := json.Unmarshal(raw, &pr); err != nil {
			return err
		}
		okStr, ms, errs := summarizePrewarmResults(pr.Results)
		rows = append(rows, []string{name, target, okStr, ms, errs})
	}
	o.table("AGENT\tTARGET\tOK\tMS\tERROR", rows)
	return nil
}
