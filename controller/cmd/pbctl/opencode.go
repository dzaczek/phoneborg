// Paths inside a project; -global switches them to the layout of opencode's
// global config directory (useGlobalLayout).
var (
	ocAgentDirName = ".opencode/agent"
	ocManifestPath = ".opencode/phoneborg-managed.json"
	// ocInstructionsPath is the managed instructions file listed in the
	// config's "instructions", telling the main agent when to delegate.
	ocInstructionsPath = ".opencode/phoneborg.md"
)

// useGlobalLayout switches to opencode's global config directory layout
// (agents in agent/, files next to the config) and returns the undo.
func useGlobalLayout() func() {
	a, m, i := ocAgentDirName, ocManifestPath, ocInstructionsPath
	ocAgentDirName, ocManifestPath, ocInstructionsPath = "agent", "phoneborg-managed.json", "phoneborg.md"
	return func() { ocAgentDirName, ocManifestPath, ocInstructionsPath = a, m, i }
}

// ocGlobalDir is opencode's global config directory.
func ocGlobalDir() string {
	base := os.Getenv("XDG_CONFIG_HOME")
	if base == "" {
		home, _ := os.UserHomeDir()
		base = filepath.Join(home, ".config")
	}
	return filepath.Join(base, "opencode")
}

