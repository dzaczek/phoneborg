func opencodeInit(c *client, o *out, args []string) error {
	fs := flag.NewFlagSet("opencode init", flag.ContinueOnError)
	fs.SetOutput(io.Discard)
	dir := fs.String("dir", ".", "project directory")
	global := fs.Bool("global", false, "use opencode's global config directory (~/.config/opencode): agents and instructions for every project; the config file is not changed")
	provider := fs.String("provider", ocProviderDefault, "opencode provider id")
	baseURL := fs.String("base-url", "", "gateway base URL (default: controller URL + /v1)")
	force := fs.Bool("force", false, "replace an existing provider block in plain JSON")
	readTools := fs.Bool("read-tools", false, "allow read, grep and glob tools instead of none (~1k extra prompt tokens per call)")
	smallModel := fs.Bool("small-model", false, "set opencode's small_model (session titles) to <provider>/pool/fast if unset")
	if err := fs.Parse(args); err != nil {
		return fmt.Errorf("opencode init: %w", err)
	}
	if *global {
		defer useGlobalLayout()()
		*dir = ocGlobalDir()
	}
	if fs.NArg() != 0 {
		return errUsage
	}

	url := *baseURL
	if url == "" {
		url = c.base + "/v1"
	}

	if err := ensureFastPool(c, o); err != nil {
		return err
	}

	state, err := fetchClusterState(c)
	if err != nil {
		return err
	}

	block := buildProviderBlock(url, state.Models, state.Nodes)
	var configPath string
	var managed, wrote bool
	if *global {
		// The global config is the user's own (often JSONC with comments):
		// say what to add instead of rewriting it.
		snippet, _ := json.MarshalIndent(map[string]any{
			"instructions": []string{filepath.Join(*dir, ocInstructionsPath)},
			"mcp":          map[string]any{*provider: buildMCPServer(c.base)},
		}, "", "  ")
		fmt.Fprintf(o.w, "global mode: %s is not changed; make sure it has the %q provider and these entries:\n%s\n", *dir, *provider, snippet)
	} else if configPath, managed, wrote, err = opencodeWriteConfig(*dir, *provider, block, *force, o); err != nil {
		return err
	}
	small := ""
	if *smallModel {
		small = *provider + "/" + poolPrefixFast
	}
	if *global {
		// nothing: the snippet above covers it
	} else if wrote { // a config left alone stays untouched
		if err := addConfigExtras(configPath, *provider, buildMCPServer(c.base), small, o); err != nil {
			return err
		}
	} else {
		snippet, _ := json.MarshalIndent(map[string]any{*provider: buildMCPServer(c.base)}, "", "  ")
		fmt.Fprintf(o.w, "to use the cluster as MCP tools, add under \"mcp\":\n%s\n", snippet)
		fmt.Fprintf(o.w, "and add %q to \"instructions\"\n", ocInstructionsPath)
	}

	manifest := ocManifest{Version: 1, Provider: *provider, BaseURL: url, ReadTools: *readTools,
		ConfigManaged: managed, Files: map[string]string{}}
	if configPath != "" {
		manifest.ConfigPath = relPath(*dir, configPath)
	}
	if managed {
		if data, err := os.ReadFile(configPath); err == nil {
			manifest.Files[manifest.ConfigPath] = sha256Hex(data)
		}
	}

	aliased := aliasedNodesFromModels(state.Models, state.Nodes)
	specs := managedAgentSpecs(*provider, *readTools, hasModel(state.Models, ocCodePool), aliased)
	res, err := syncAgentFiles(*dir, specs, &manifest)
	if err != nil {
		return err
	}
	if _, warn, err := syncInstructions(*dir, renderInstructions(specs, superborgPoolNames(c)), &manifest); err != nil {
		return err
	} else if warn != "" {
		res.Warnings = append(res.Warnings, warn)
	}
	manifest.UpdatedAt = time.Now().UTC()
	if err := manifest.save(*dir); err != nil {
		return err
	}

	fmt.Fprintf(o.w, "agents: %s\n", res.summary())
	for _, w := range res.Warnings {
		fmt.Fprintln(o.w, "warning:", w)
	}
	if *readTools {
		fmt.Fprintln(o.w, "note:", ocReadToolsNoteWords)
	}
	return nil
}

