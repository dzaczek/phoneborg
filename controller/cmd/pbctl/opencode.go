// renderInstructions tells opencode's main agent when and how to delegate to
// the cluster: the generated subagents, the MCP tools and the Super Borg
// pools jobs can run on.
func renderInstructions(specs []ocAgentSpec, borgPools []string) string {
	var b strings.Builder
	b.WriteString(ocGeneratedMarker + "\n")
	b.WriteString(`# PhoneBorg cluster

This project can use PhoneBorg, a cluster of phones running small language
models. They are slow (a few tokens per second each) but free, and several
run in parallel. Delegate to them when it saves you work; keep planning,
hard reasoning, code edits and final decisions yourself.

## Subagents (Task tool)

`)
	for _, s := range specs {
		fmt.Fprintf(&b, "- @%s: %s\n", s.Name, s.Description)
	}
	b.WriteString(`
Start several at once for independent pieces, e.g. @borg-review on the diff
and @borg-summarize on the description in parallel.

## MCP tools (server "phoneborg")

- cluster_map: several independent, self-contained tasks at once, spread
  over the phones (model "pool/code" for code, "pool/fast" for simple text);
  returns every answer numbered. Cheaper than one subagent per task.
- cluster_vote: the same question to several phones, each answering one of
  the options with a reason; returns the votes, the majority and, with a
  threshold such as "4/5", PASS or FAIL. Use it as a quality gate.
- ask_cluster: one small prompt.
- job_start, job_wait, job_status, job_message, job_result: long work in
  many parts (a document in chapters, many similar items). A job plans and
  writes in the background for minutes to hours`)
	if len(borgPools) > 0 {
		fmt.Fprintf(&b, " on a Super Borg pool (%s)", strings.Join(borgPools, ", "))
	}
	b.WriteString(`.
  Start it, then follow it with job_wait (it returns when something
  changes) instead of asking again and again; fetch the text with
  job_result when it is done.
- cluster_status: which phones and pools are ready.

## How to work with the cluster

1. Plan the work yourself and cut it into pieces a small model can do from
   the text you send: one function, one test file, one section, one review.
2. Send independent pieces together with cluster_map (or several subagents).
3. Check the results yourself: run the tests and the build, read the
   output; for judgement calls use cluster_vote with a threshold.
4. Send back only what failed, with the error, and repeat until it passes.
5. You apply all edits to the repository and decide when the task is done.

## Rules

- The phones see only what you send: include the code or text they need,
  and keep each piece well under 8k tokens (they have a 16k context and
  read about 10–20 tokens per second).
- Small models make mistakes: check their output before you use it.
- Never send secrets, credentials or private data to the cluster.
- Edits to the repository and tool use on it stay with you.
`)
	return b.String()
}

// syncInstructions writes the instructions file unless it was edited by
// hand since pbctl last wrote it.
func syncInstructions(dir, content string, manifest *ocManifest) (changed bool, warn string, err error) {
	full := filepath.Join(dir, ocInstructionsPath)
	data, err := os.ReadFile(full)
	switch {
	case errors.Is(err, os.ErrNotExist):
	case err != nil:
		return false, "", err
	case manifest.Files[ocInstructionsPath] != "" && sha256Hex(data) != manifest.Files[ocInstructionsPath]:
		return false, ocInstructionsPath + " was edited by hand; left as is", nil
	case string(data) == content:
		manifest.Files[ocInstructionsPath] = sha256Hex(data)
		return false, "", nil
	}
	if err := os.MkdirAll(filepath.Dir(full), 0o755); err != nil {
		return false, "", err
	}
	if err := os.WriteFile(full, []byte(content), 0o644); err != nil {
		return false, "", err
	}
	manifest.Files[ocInstructionsPath] = sha256Hex([]byte(content))
	return true, "", nil
}

// superborgPoolNames lists "pool/<name>" of the Super Borg pools; a
// controller without the pools API yields none.
func superborgPoolNames(c *client) []string {
	raw, err := c.do(http.MethodGet, "/admin/pools", nil)
	if err != nil {
		return nil
	}
	var l ocPoolList
	if json.Unmarshal(raw, &l) != nil {
		return nil
	}
	var out []string
	for _, p := range l.Pools {
		if p.Routing == "superborg" {
			out = append(out, "pool/"+p.Name)
		}
	}
	return out
}

