type ocProviderOptions struct {
	BaseURL       string `json:"baseURL"`
	APIKey        string `json:"apiKey"`
	Timeout       bool   `json:"timeout"`
	HeaderTimeout int    `json:"headerTimeout"`
	ChunkTimeout  int    `json:"chunkTimeout"`
}

type ocProviderBlock struct {
	NPM     string                     `json:"npm"`
	Name    string                     `json:"name"`
	Options ocProviderOptions          `json:"options"`
	Models  map[string]ocProviderModel `json:"models"`
}

type ocProviderWrapper struct {
	Provider map[string]ocProviderBlock `json:"provider"`
}

func buildProviderBlock(baseURL string, models []ocModel, nodes []ocAdminNode) ocProviderBlock {
	pb := ocProviderBlock{
		NPM:  "@ai-sdk/openai-compatible",
		Name: "PhoneBorg",
		Options: ocProviderOptions{
			BaseURL: baseURL, APIKey: "{env:PHONEBORG_API_KEY}",
			Timeout: false, HeaderTimeout: 1800000, ChunkTimeout: 1800000,
		},
		Models: map[string]ocProviderModel{},
	}
	for _, m := range models {
		pb.Models[m.ID] = ocProviderModel{
			Name:  modelDisplayName(m, nodes),
			Limit: ocLimit{Context: modelContextLimit(m, nodes), Output: ocOutputLimit},
		}
	}
	return pb
}

// hasJSONComments reports whether data contains a // or /* */ comment
// outside of a string literal, i.e. it is JSONC, not plain JSON.
func hasJSONComments(data []byte) bool {
	inString, escaped := false, false
	for i := 0; i < len(data); i++ {
		c := data[i]
		if inString {
			switch {
			case escaped:
				escaped = false
			case c == '\\':
				escaped = true
			case c == '"':
				inString = false
			}
			continue
		}
		switch {
		case c == '"':
			inString = true
		case c == '/' && i+1 < len(data) && (data[i+1] == '/' || data[i+1] == '*'):
			return true
		}
	}
	return false
}

func isJSONCConfig(path string, data []byte) bool {
	if strings.EqualFold(filepath.Ext(path), ".jsonc") {
		return true
	}
	return hasJSONComments(data)
}

// plainJSONHasProviderKey reports whether root.provider.<provider> exists in
// a strict-JSON config.
func plainJSONHasProviderKey(data []byte, provider string) (bool, error) {
	var root map[string]json.RawMessage
	if err := json.Unmarshal(data, &root); err != nil {
		return false, err
	}
	raw, ok := root["provider"]
	if !ok {
		return false, nil
	}
	var providers map[string]json.RawMessage
	if err := json.Unmarshal(raw, &providers); err != nil {
		return false, err
	}
	_, ok = providers[provider]
	return ok, nil
}

// mergeProviderBlockJSON sets root.provider.<provider> = block in a strict
// JSON document, leaving every other key (and every other provider) as it
// was. Key order is not preserved (encoding/json sorts map keys), but every
// value is.
func mergeProviderBlockJSON(data []byte, provider string, block ocProviderBlock) ([]byte, error) {
	var root map[string]json.RawMessage
	if err := json.Unmarshal(data, &root); err != nil {
		return nil, fmt.Errorf("parse config: %w", err)
	}
	if root == nil {
		root = map[string]json.RawMessage{}
	}
	var providers map[string]json.RawMessage
	if raw, ok := root["provider"]; ok {
		if err := json.Unmarshal(raw, &providers); err != nil {
			return nil, fmt.Errorf("parse provider block: %w", err)
		}
	}
	if providers == nil {
		providers = map[string]json.RawMessage{}
	}
	blockRaw, err := json.Marshal(block)
	if err != nil {
		return nil, err
	}
	providers[provider] = blockRaw
	providersRaw, err := json.Marshal(providers)
	if err != nil {
		return nil, err
	}
	root["provider"] = providersRaw
	out, err := json.MarshalIndent(root, "", "  ")
	if err != nil {
		return nil, err
	}
	return append(out, '\n'), nil
}

func fileExists(path string) bool {
	_, err := os.Stat(path)
	return err == nil
}

func backupFile(path string) error {
	data, err := os.ReadFile(path)
	if err != nil {
		return err
	}
	return os.WriteFile(path+".bak", data, 0o644)
}

func printProviderBlockToPaste(o *out, provider string, block ocProviderBlock, path string) {
	data, _ := json.MarshalIndent(block, "", "  ")
	fmt.Fprintf(o.w, "%s already configures opencode; paste this under \"provider\":\n\n\"%s\": %s\n\n", path, provider, data)
}

// opencodeWriteConfig implements the init config rules: create a fresh
// opencode.json when neither file exists; merge into an existing plain JSON
// file that lacks the provider (or, with force, replace it); otherwise
// (JSONC, or already configured without force) leave the file untouched and
// print the block to paste. managed is true only when this call created the
// file from scratch.
func opencodeWriteConfig(dir, provider string, block ocProviderBlock, force bool, o *out) (path string, managed bool, err error) {
	jsonPath := filepath.Join(dir, "opencode.json")
	jsoncPath := filepath.Join(dir, "opencode.jsonc")
	jsonExists, jsoncExists := fileExists(jsonPath), fileExists(jsoncPath)

	if !jsonExists && !jsoncExists {
		wrapper := ocProviderWrapper{Provider: map[string]ocProviderBlock{provider: block}}
		data, err := json.MarshalIndent(wrapper, "", "  ")
		if err != nil {
			return "", false, err
		}
		data = append(data, '\n')
		if err := gateway.WriteFileAtomic(jsonPath, data, 0o644); err != nil {
			return "", false, err
		}
		fmt.Fprintf(o.w, "wrote %s\n", jsonPath)
		return jsonPath, true, nil
	}

	path = jsoncPath
	if jsonExists {
		path = jsonPath
	}
	data, err := os.ReadFile(path)
	if err != nil {
		return "", false, err
	}

	if isJSONCConfig(path, data) {
		printProviderBlockToPaste(o, provider, block, path)
		return path, false, nil
	}

	hasProvider, err := plainJSONHasProviderKey(data, provider)
	if err != nil {
		// Malformed despite having no comments: be safe, don't touch it.
		printProviderBlockToPaste(o, provider, block, path)
		return path, false, nil
	}
	if hasProvider && !force {
		printProviderBlockToPaste(o, provider, block, path)
		return path, false, nil
	}

	merged, err := mergeProviderBlockJSON(data, provider, block)
	if err != nil {
		return "", false, err
	}
	if err := backupFile(path); err != nil {
		return "", false, err
	}
	if err := gateway.WriteFileAtomic(path, merged, 0o644); err != nil {
		return "", false, err
	}
	verb := "merged provider block into"
	if hasProvider {
		verb = "replaced provider block in"
	}
	fmt.Fprintf(o.w, "%s %s (backup at %s.bak)\n", verb, path, path)
	return path, false, nil
}

// ---- agent file rendering ----

type ocAgentSpec struct {
	Name        string
	Description string
	Model       string
	ReadTools   bool
	Body        string
}

func renderAgent(spec ocAgentSpec) string {
	var b strings.Builder
	b.WriteString("---\n")
	fmt.Fprintf(&b, "description: %s\n", spec.Description)
	b.WriteString("mode: subagent\n")
	fmt.Fprintf(&b, "model: %s\n", spec.Model)
	b.WriteString("tools:\n")
	b.WriteString("  \"*\": false\n")
	if spec.ReadTools {
		b.WriteString("  read: true\n")
		b.WriteString("  grep: true\n")
		b.WriteString("  glob: true\n")
	}
	b.WriteString("---\n")
	b.WriteString(strings.TrimRight(spec.Body, "\n"))
	b.WriteString("\n\n")
	b.WriteString(ocGeneratedMarker)
	b.WriteString("\n")
	return b.String()
}

// parseAgentFrontmatter extracts the "model:" value and the prompt body (the
// generated-by marker stripped) from a rendered agent file. It is the
// inverse of renderAgent.
func parseAgentFrontmatter(content string) (model, body string, err error) {
	const openFence = "---\n"
	if !strings.HasPrefix(content, openFence) {
		return "", "", errors.New("agent file: missing frontmatter")
	}
	rest := content[len(openFence):]
	idx := strings.Index(rest, "\n---\n")
	if idx < 0 {
		return "", "", errors.New("agent file: unterminated frontmatter")
	}
	for _, line := range strings.Split(rest[:idx], "\n") {
		if v, ok := strings.CutPrefix(line, "model:"); ok {
			model = strings.TrimSpace(v)
		}
	}
	if model == "" {
		return "", "", errors.New("agent file: missing model")
	}
	body = rest[idx+len("\n---\n"):]
	body = strings.TrimSuffix(body, "\n"+ocGeneratedMarker+"\n")
	body = strings.TrimSuffix(body, "\n"+ocGeneratedMarker)
	body = strings.TrimRight(body, "\n")
	return model, body, nil
}

