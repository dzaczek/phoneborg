// ocAdminNode is the slice of GET /admin/nodes this command needs: id, alias
// (once the alias PATCH lands), device and served model/context.
type ocAdminNode struct {
	ID        string `json:"id"`
	Alias     string `json:"alias"`
	Inventory struct {
		Manufacturer string `json:"manufacturer"`
		Model        string `json:"model"`
	} `json:"inventory"`
	LastHeartbeat *struct {
		Runtime *struct {
			Model   string `json:"model"`
			Ready   bool   `json:"ready"`
			CtxSize int    `json:"ctx_size"`
		} `json:"runtime"`
	} `json:"last_heartbeat"`
}

func (n ocAdminNode) device() string {
	return strings.TrimSpace(n.Inventory.Manufacturer + " " + n.Inventory.Model)
}

func (n ocAdminNode) servedModel() string {
	if n.LastHeartbeat != nil && n.LastHeartbeat.Runtime != nil {
		return n.LastHeartbeat.Runtime.Model
	}
	return ""
}

func (n ocAdminNode) ctxSize() int {
	if n.LastHeartbeat != nil && n.LastHeartbeat.Runtime != nil {
		return n.LastHeartbeat.Runtime.CtxSize
	}
	return 0
}

