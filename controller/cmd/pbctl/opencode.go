func opencodeCmd(c *client, o *out, rest []string) error {
	if len(rest) == 0 {
		return errUsage
	}
	sub, args := rest[0], rest[1:]
	switch sub {
	case "init":
		return opencodeInit(c, o, args)
	case "sync":
		return opencodeSync(c, o, args)
	case "watch":
		return opencodeWatch(c, o, args)
	case "status":
		return opencodeStatus(c, o, args)
	case "prewarm":
		return opencodePrewarm(c, o, args)
	}
	return errUsage
}

