type ocManifest struct {
	Version       int               `json:"version"`
	Provider      string            `json:"provider"`
	BaseURL       string            `json:"base_url"`
	ReadTools     bool              `json:"read_tools"`
	ConfigPath    string            `json:"config_path,omitempty"`
	ConfigManaged bool              `json:"config_managed"`
	Files         map[string]string `json:"files"`
	UpdatedAt     time.Time         `json:"updated_at"`
}

func (m ocManifest) agentNames() []string {
	prefix := ocAgentDirName + "/"
	var names []string
	for rel := range m.Files {
		if !strings.HasPrefix(rel, prefix) || !strings.HasSuffix(rel, ".md") {
			continue
		}
		names = append(names, strings.TrimSuffix(strings.TrimPrefix(rel, prefix), ".md"))
	}
	sort.Strings(names)
	return names
}

func loadManifest(dir string) (ocManifest, bool, error) {
	data, err := os.ReadFile(filepath.Join(dir, ocManifestPath))
	if errors.Is(err, os.ErrNotExist) {
		return ocManifest{}, false, nil
	}
	if err != nil {
		return ocManifest{}, false, err
	}
	var m ocManifest
	if err := json.Unmarshal(data, &m); err != nil {
		return ocManifest{}, false, err
	}
	if m.Files == nil {
		m.Files = map[string]string{}
	}
	return m, true, nil
}

func (m ocManifest) save(dir string) error {
	path := filepath.Join(dir, ocManifestPath)
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		return err
	}
	data, err := json.MarshalIndent(m, "", "  ")
	if err != nil {
		return err
	}
	return gateway.WriteFileAtomic(path, append(data, '\n'), 0o644)
}

func sha256Hex(data []byte) string {
	sum := sha256.Sum256(data)
	return hex.EncodeToString(sum[:])
}

func relPath(dir, path string) string {
	rel, err := filepath.Rel(dir, path)
	if err != nil {
		return path
	}
	return filepath.ToSlash(rel)
}

// ocSyncResult is a diff summary: which managed files were added, removed,
// regenerated because their template changed, or left as is.
type ocSyncResult struct {
	Added, Removed, Updated, Kept []string
	Warnings                      []string
}

func (r ocSyncResult) changed() bool {
	return len(r.Added) > 0 || len(r.Removed) > 0 || len(r.Updated) > 0
}

func (r ocSyncResult) summary() string {
	return fmt.Sprintf("added %d, removed %d, updated %d, kept %d", len(r.Added), len(r.Removed), len(r.Updated), len(r.Kept))
}

// syncAgentFiles writes every wanted agent spec under dir/.opencode/agent,
// removes managed files that are no longer wanted (unless hand-edited), and
// updates manifest.Files in place. It is idempotent: running it twice with
// the same specs yields an all-kept result.
func syncAgentFiles(dir string, specs []ocAgentSpec, manifest *ocManifest) (ocSyncResult, error) {
	agentDir := filepath.Join(dir, ocAgentDirName)
	if err := os.MkdirAll(agentDir, 0o755); err != nil {
		return ocSyncResult{}, err
	}

	var res ocSyncResult
	wanted := map[string]bool{}
	for _, spec := range specs {
		rel := ocAgentDirName + "/" + spec.Name + ".md"
		wanted[rel] = true
		content := renderAgent(spec)
		hash := sha256Hex([]byte(content))
		full := filepath.Join(dir, rel)
		existingHash, tracked := manifest.Files[rel]

		data, readErr := os.ReadFile(full)
		switch {
		case errors.Is(readErr, os.ErrNotExist):
			if err := os.WriteFile(full, []byte(content), 0o644); err != nil {
				return res, err
			}
			manifest.Files[rel] = hash
			res.Added = append(res.Added, rel)
		case readErr != nil:
			return res, readErr
		case tracked && sha256Hex(data) != existingHash:
			res.Warnings = append(res.Warnings, fmt.Sprintf("%s was edited by hand; left as is", rel))
			res.Kept = append(res.Kept, rel)
		case string(data) == content:
			manifest.Files[rel] = hash
			res.Kept = append(res.Kept, rel)
		default:
			if err := os.WriteFile(full, []byte(content), 0o644); err != nil {
				return res, err
			}
			manifest.Files[rel] = hash
			res.Updated = append(res.Updated, rel)
		}
	}

	prefix := ocAgentDirName + "/"
	for rel, hash := range manifest.Files {
		if !strings.HasPrefix(rel, prefix) || wanted[rel] {
			continue
		}
		full := filepath.Join(dir, rel)
		data, err := os.ReadFile(full)
		if errors.Is(err, os.ErrNotExist) {
			delete(manifest.Files, rel)
			continue
		}
		if err != nil {
			return res, err
		}
		if sha256Hex(data) != hash {
			res.Warnings = append(res.Warnings, fmt.Sprintf("%s was edited by hand; not removing", rel))
			continue
		}
		if err := os.Remove(full); err != nil {
			return res, err
		}
		delete(manifest.Files, rel)
		res.Removed = append(res.Removed, rel)
	}

	sort.Strings(res.Added)
	sort.Strings(res.Removed)
	sort.Strings(res.Updated)
	sort.Strings(res.Kept)
	return res, nil
}

// syncManagedConfig refreshes a managed (init-created) plain-JSON config's
// provider models list, unless it was hand-edited since it was generated.
func syncManagedConfig(dir string, manifest *ocManifest, block ocProviderBlock) (changed bool, warn string, err error) {
	if !manifest.ConfigManaged || manifest.ConfigPath == "" {
		return false, "", nil
	}
	full := filepath.Join(dir, manifest.ConfigPath)
	data, err := os.ReadFile(full)
	if errors.Is(err, os.ErrNotExist) {
		return false, "", nil
	}
	if err != nil {
		return false, "", err
	}
	if h, ok := manifest.Files[manifest.ConfigPath]; ok && sha256Hex(data) != h {
		return false, fmt.Sprintf("%s was edited by hand; not updating its model list", manifest.ConfigPath), nil
	}
	wrapper := ocProviderWrapper{Provider: map[string]ocProviderBlock{manifest.Provider: block}}
	newData, err := json.MarshalIndent(wrapper, "", "  ")
	if err != nil {
		return false, "", err
	}
	newData = append(newData, '\n')
	if string(newData) == string(data) {
		return false, "", nil
	}
	if err := gateway.WriteFileAtomic(full, newData, 0o644); err != nil {
		return false, "", err
	}
	manifest.Files[manifest.ConfigPath] = sha256Hex(newData)
	return true, "", nil
}

// runOpenCodeSync does the work of "pbctl opencode sync" without printing
// anything, so both the sync command and watch's loop can share it.
func runOpenCodeSync(c *client, dir string) (ocSyncResult, error) {
	manifest, ok, err := loadManifest(dir)
	if err != nil {
		return ocSyncResult{}, err
	}
	if !ok {
		return ocSyncResult{}, fmt.Errorf("no %s; run 'pbctl opencode init' first", filepath.Join(dir, ocManifestPath))
	}

	state, err := fetchClusterState(c)
	if err != nil {
		return ocSyncResult{}, err
	}

	aliased := aliasedNodesFromModels(state.Models, state.Nodes)
	specs := managedAgentSpecs(manifest.Provider, manifest.ReadTools, aliased)
	res, err := syncAgentFiles(dir, specs, &manifest)
	if err != nil {
		return res, err
	}

	if manifest.ConfigManaged {
		block := buildProviderBlock(manifest.BaseURL, state.Models, state.Nodes)
		changedCfg, warn, err := syncManagedConfig(dir, &manifest, block)
		if err != nil {
			return res, err
		}
		if warn != "" {
			res.Warnings = append(res.Warnings, warn)
		}
		if changedCfg {
			res.Updated = append(res.Updated, manifest.ConfigPath)
			sort.Strings(res.Updated)
		}
	}

	manifest.UpdatedAt = time.Now().UTC()
	if err := manifest.save(dir); err != nil {
		return res, err
	}
	return res, nil
}

